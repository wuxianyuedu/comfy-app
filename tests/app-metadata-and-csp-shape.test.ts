/**
 * 应用外壳两处「用户可见但没人守」的形状：窗口元数据（create-t3-app 残留 "Create T3 App"）与 CSP 求值时机
 * （每请求重拼一遍字符串）。不真求值 `next.config.js`：它顶层 `import "./src/env.js"` 要 `.env`（缺了直接抛错），
 * 进单测就是依赖本机环境。故只钉「常量在不在、`headers()` 不退回逐请求拼装」；等价性已实测（prod 352 / dev 366 字节，需 `SKIP_ENV_VALIDATION=1`）。
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

const root = path.resolve(__dirname, "..");
const nextConfig = readFileSync(path.join(root, "next.config.js"), "utf8");
const layout = readFileSync(path.join(root, "src", "app", "layout.tsx"), "utf8");
const modelsPage = readFileSync(
  path.join(root, "src", "app", "(main)", "models", "page.tsx"),
  "utf8",
);

/** 取某个导出对象字面量的正文（`export const x … = { … }` 那一段）。 */
function exportedObjectBody(source: string, exportName: string): string {
  const start = source.indexOf(`export const ${exportName}`);
  if (start === -1) {
    return "";
  }
  const open = source.indexOf("{", start);
  if (open === -1) {
    return "";
  }
  // 单行（`{ title: "模型库" }`）与多行（`{\n  …\n}`）两种收尾都要认。
  const end = source.indexOf("}", open);
  return end === -1 ? "" : source.slice(open, end + 1);
}

describe("根布局的窗口元数据不再是脚手架残留", () => {
  /* 只在**代码**里判，不判全文：上面那段注释正是在讲「它曾经是脚手架残留」，
   * 全文匹配会把「讲清楚为什么改」的注释一起判红（假判据反而逼人删注释）。 */
  it("title / description 里没有 create-t3-app 的原样值", () => {
    const body = exportedObjectBody(layout, "metadata");
    expect(body, "根布局里找不到 metadata 导出").toBeTruthy();
    expect(body).not.toContain("Create T3 App");
    expect(body).not.toContain("Generated by create-t3-app");
  });

  it("title 走 template，品牌只在根布局收口一处", () => {
    expect(layout).toContain('default: "Comfy-APP"');
    expect(layout).toContain("template:");
  });

  /* 反向锚点：`themeColor` 曾被顺手加进来，又在核实「谁消费它」之后去掉 ——
   * 桌面壳 `decorations: false`、窗口底色归 `tauri.conf.json`，这颗 meta 管的是
   * 浏览器地址栏/窗饰，本应用没有消费方。这条钉住「别再凭印象补回来」。 */
  it("没有凭印象补 viewport.themeColor（本应用没有消费方）", () => {
    // 只判「有没有那个导出」：上面那段注释正是在解释为什么**不**加它，
    // 连注释一起判会把「把理由写清楚」的人判红。
    expect(layout).not.toContain("export const viewport");
  });

  /* 子路由只写自己那一段 —— 品牌由根 template 补。这条锁「两处配合之后
   * 仍是「模型库 · Comfy-APP」」：models 页的 metadata 一旦自己带上品牌，
   * 根 template 会再补一遍，标题就成了「模型库 · Comfy-APP · Comfy-APP」。 */
  it("models 页只声明本页那一段，品牌靠根 template 补齐", () => {
    const body = exportedObjectBody(modelsPage, "metadata");
    expect(body, "models 页里找不到 metadata 导出").toBeTruthy();
    expect(body).toContain('title: "模型库"');
    expect(body, "models 页自带品牌后又会被根 template 补一遍，标题会重复").not.toContain(
      "Comfy-APP",
    );
  });
});

describe("CSP 是模块级常量，不是逐请求现拼", () => {
  it("CSP 在模块级算一次（`headers()` 里没有 join 出来的那份拼装）", () => {
    expect(nextConfig).toContain("const CSP = [");
    const headersBody = /async headers\(\)\s*\{(?<body>[\s\S]*?)\n {2}\},/.exec(nextConfig)?.groups
      ?.body;
    expect(headersBody, "next.config.js 里找不到 headers()").toBeTruthy();
    expect(
      headersBody,
      "headers() 又退回逐请求拼 CSP 了（拼接应留在模块级的 CSP 常量里）",
    ).not.toContain(".join(");
  });

  it("dev / prod 两态都在：dev 必须放行 unsafe-eval，prod 不许", () => {
    expect(nextConfig).toContain("'unsafe-eval'");
    expect(nextConfig).toMatch(/IS_DEV\s*\?/);
  });

  /* 这三条是 CSP 里「删掉就静默失去某功能」的项，各自都有历史事故：
   * frame-src 少了 ComfyUI 页签只剩「已阻止此内容」；connect-src 少了
   * Tauri 事件监听静默失效（命令还照常能调通）；frame-ancestors 'none'
   * 是本应用不被别站内嵌的反点击劫持。 */
  it("三条承重条目仍在（frame-src / ipc 通道 / frame-ancestors）", () => {
    expect(nextConfig).toContain("frame-src 'self' http://127.0.0.1:*");
    expect(nextConfig).toContain("ipc: http://ipc.localhost");
    expect(nextConfig).toContain("frame-ancestors 'none'");
  });
});
