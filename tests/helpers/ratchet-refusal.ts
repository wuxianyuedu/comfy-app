/**
 * 「棘轮拒涨那一刻说的话，必须给出上涨态里可执行的下一步」—— 这一条判据的**唯一实现**。
 *
 * 为什么要有这个文件（而不是各家测试里各写一遍）：这条性质原先只住在
 * `tests/ratchet-update-guards.test.ts` 的第 ⑥ 步里，而它跑的范围只有 `RATCHETS` 那张表。
 * 另外几家被归进 `COVERED_LOCALLY`（沙箱造不出它们的输入面），归类语句写的是
 * 「本地用例覆盖了拒涨」—— 实测那四份本地用例钉住的都是**退出码 + 句子里的一个短语**
 * （`toContain("拒绝把基线往上涨")` 那一形），而「出路是不是死路」这半边谁都没判过。
 * 于是「表里点名了 = 判过了」是一句没有执行者的声明（§11.2.1 那一族：假保险的登记形态）。
 *
 * `check-tsc-diagnostic-executors.cjs` 是这一族唯一落了地的现场：它的红话写着
 * 「再跑 `--update`（= 把基线收紧到 N）」，而同一个 `--update` 对上涨正是非零拒绝 ——
 * 照它跑只会再吃一次红，真问题一次都没被回答。红话与机制相反，比没有红话更糟。
 *
 * 四种自洽写法都算通过：**先改再 `--update`**（把顺序写明）、**明说不要用 `--update`**
 * （把这条堵死）、**改成人的动作**（手工登记 / 逐条写理由）、**例外流程另给一个显式旗标**
 * （`check-bundle-budget.cjs` 那一形：贴 before/after 读数 + 评审确认后带
 * `--allow-increase` 重跑 —— 认的是「另一个必须认账才敲得动的动作」，所以这个分支
 * 刻意**不认 `--update` 本身**，否则 `check-tsc-diagnostic-executors.cjs` 那个原始现场
 *（红话把人指回同一个会拒绝的旗标）就又被放过去了）。
 */
import { expect } from "vitest";

/**
 * 上涨态里「可执行的下一步」的四种形状（判的是那句话，不是脚本里随便哪行注释）。
 *
 * 第二个分支认的是**明说不要用**这一族，措辞按实到的三种收：`不要用` / `不许用` /
 * `不给`（`check-tsc-diagnostic-executors.cjs` 写的是「这一步**不给 `--update`**」）。
 * 这里刻意按形状而不是按整句字面量收 —— 一句红话换个性别的说法就把自己判红，
 * 那种判据下一次会被当成噪音绕过去。
 */
export const ACTIONABLE_REFUSAL =
  /先[\s\S]{0,240}?(再|之后)[\s\S]{0,60}--update|不(要用|许用|给)\s*`?--update`?|`?--update`?\s*(是|只用于|不能拿来|拒绝)|(手工|逐条)[\s\S]{0,60}(登记|改|写)|带\s*`?--(?!update)[a-z][a-z-]*`?/;

/**
 * 断一次「`--update` 拒涨」的输出。
 *
 * 调用点必须传**拒涨那一刻**捕获到的输出（退出码已经判过非零的那一次），不要传
 * 收紧成功那一次的输出 —— 那时这句话本来就不该出现，判它等于判空气。
 */
export function expectActionableRefusal(output: string, who: string): void {
  expect(
    output,
    `${who}：--update 拒涨了，但红话没给出上涨态里可执行的下一步` +
      `（四种自洽写法见本文件头：先改再 --update / 明说不要用 --update / 改成人的动作 /` +
      ` 例外流程另给一个显式认账旗标）。\n${output}`,
  ).toMatch(ACTIONABLE_REFUSAL);
}
