/**
 * 浮层层级（z-index）的刻度表 —— 规范 16 §16.2.5。
 *
 * 背景（ISSUE #672）：同一件事（下拉浮层）曾在 `MultiSegmentPopover` 是
 * `9999`、`WorkflowSeedModeButton` 是 `9999` 配 `9998` 遮罩、`SelectMenu`
 * 又是 `9999`，而节点 JSON 浮层用 `9000`/`9001`，全屏抽屉散落
 * `10005`/`10020`；状态栏 `10000`、消息中心 `10020` —— 谁也说不清「它比谁高」，
 * 新增一层只能再编一个更大的数。
 *
 * P2 先把自搓浮层收拢到 `ui/` 原语并定下两条刻度；P4 发现**余量仍有 7 处自成
 * 一档**（`9998` / `z-[10000]` / `z-[10020]` / `z-80` / `z-60` / `studio/logs`
 * 的 `z-99`+`z-200`），于是把刻度补成一张**成体系的表**：每一档都对得上一类
 * 真实存在的浮层关系，而不是「再把魔数换个名字写进对象里」。
 *
 * 数值同时定义在 `src/app/globals.css` 的 `@theme`（供 `z-overlay` /
 * `z-popup` / `z-modal` / `z-canvas-ui` 等工具类使用），两处必须一致 ——
 * 由 `tests/overlay-z-scale.test.ts` 钉住。放在 `lib/shell`：它是**客户端可达**
 * 的跨端定层常量，`lib/core` 在 eslint 的 boundaries 里是 element `server`，
 * 视图层引不得。
 *
 * ── 刻度（越小越靠下）────────────────────────────────────────────
 * | 档            | 值   | 谁在这一档                                             |
 * |---------------|------|--------------------------------------------------------|
 * | `base`        | 10   | 局部叠层下限：画布节点内容 / 子图、卡片内遮罩 —— 参照点 |
 * |               |      | 是自己的**定位祖先**，比较对象在容器内部，不进视口刻度   |
 * | `canvasUi`    | 20   | 画布 chrome：工具栏 / 侧栏 / 面板 / 角标提示            |
 * | `canvasMax`   | 30   | 画布最上层：IO 预览 / 底部工具栏                        |
 * | `modal`       | 90   | 模态遮罩与抽屉 —— 应用内的「顶」（`overlay` 是它的旧名） |
 * | `popup`       | 100  | **挂在 body** 的浮层：下拉 / 气泡 / 节点 JSON 浮层       |
 * | `toast`       | 1000 | 全局提示，恒在最上                                      |
 *
 * ── 三条判据（与规范 §16.2.5 同源）─────────────────────────────
 * 1. **`modal` 不进 1000~1200**：那是 React Flow 给节点选中态（约 1010）与
 *    悬浮态（1180，见 `globals.css`）留的位，应用模态插进去会和节点争层级。
 * 2. **`popup` > `modal`**：挂在 body 的下拉由**模态内部**的控件打开
 *    （`ui/select` / `ui/popover` / `ui/dropdown-menu` 都是 portal 到 body），
 *    低于模态就等于「点得开、点不中」—— 同 §16.2.5 里日志面板那条回归。
 * 3. **画布内部的层级不属于本表**：指针/事件只在自己容器的层叠上下文里比较，
 *    与视口浮层不在同一维度；它们从 `base` 起排是为了「同一个容器内部的关系
 *    有名字」，而不是「要和模态比高低」。
 */
export const Z = {
  /** 局部叠层下限：画布节点内容 / 子图、卡片内遮罩。 */
  base: 10,
  /** 画布 chrome：工具栏 / 侧栏 / 面板 / 角标提示。 */
  canvasUi: 20,
  /** 画布最上层：IO 预览 / 底部工具栏。 */
  canvasMax: 30,
  /** 模态遮罩与抽屉（应用内的「顶」）。 */
  modal: 90,
  /** 挂在 body 的浮层：下拉 / 气泡 / 节点 JSON 浮层（**在模态之上**）。 */
  popup: 100,
  /** 模态档的旧名，值同 `modal`；新代码写 `modal`。 */
  overlay: 90,
  /** 全局提示（Toast 等），恒在浮层之上。 */
  toast: 1000,
} as const;

/** 刻度档名（`Z` 的键，排除 `overlay` 这个别名）。 */
export type ZTone = Exclude<keyof typeof Z, "overlay">;

/** 档名 → 工具类名（`z-modal` / `z-popup` …）。 */
export function zClass(tone: ZTone): string {
  const kebab = tone.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  return `z-${kebab}`;
}
