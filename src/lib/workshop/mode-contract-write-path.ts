// ── 模式契约**写在哪**（唯一出处，纯常量、无 IO）────────────────────────
// 为什么单独一个模块：这个路径有两类读者，而它们**都不能**引对方那一侧 ——
//   · 服务端：`mode-contract.server.ts`（带 `server-only`）据此落盘；
//   · 视图层：保存成功的提示要告诉用户「这份契约是不是在包外、会不会丢」，
//     而 `.server.ts` 引不得（§18.4 的浏览器图边界）。
// 各写一份字符串必然漂移，而漂移的表现就是「界面说的位置不是真的那个」。
//
// 契约有两种形态，这一份常量说的是**第二种**：
//   · 成品配置 —— 编译进源码的那份（纯函数层 `CONFIGURED_MODE_CONTRACTS`），
//     随构建走、到哪都是同一份，用户改不了它也不需要知道它在哪；
//   · 本机覆盖 —— 编辑器保存写出来的这份，落在本机运行期目录 `data/` 里。
// 分发产物里没有任何入口能编辑它（载荷只带生产依赖、编辑器属开发期界面），
// 所以放 `data/` 正合适：它**本就该**是「这台机器上的覆盖」，
// 而不是随包分发的项目配置（`config/` 那一层已随 ISSUE #1917 去掉）。

