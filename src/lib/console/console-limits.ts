// ── 应用内控制台的**预算常量**（纯叶子：零依赖、可被路由 / lib / 视图同时读）──
//
// 为什么单独一份而不是散在 `console-run.ts` / 路由 / 视图里各写一遍：这三个
// 数值在三个层次上被判据消费，且**它们必须同源**——
//   · 输入框的 `maxLength` 用 `MAX_COMMAND_CHARS`，路由的入参校验也用同一值：
//     两处不一致时用户能敲进去但提交被拒（「界面允许、服务端 400」），
//     而报错文案指不出「就是你敲太长」；
//   · 输出上限既决定 SSE 何时停发，也决定界面「已截断」提示是否会与事实不符；
//   · 看门狗上限要在界面上提前说清（「这条命令最多跑 N 分钟」），否则用户只会
//     觉得「跑到一半没声了」。
// 判据是「同一个数在几处出现」——同 §12.14 的端点收口，只是它的对象是预算。

/**
 * 单条命令的字符上限。
 *
 * 512 是「够长但明显不是脚本」的量级：真实要敲的命令（含几个长路径参数）都在
 * 200 以内，而 512 之上基本是「有人把整段脚本贴进来了」——那应该落成
 * `scripts/*.mjs` 或 `node -e`，而不是堆在输入框里（也没有可读的回显）。
 */
export const MAX_COMMAND_CHARS = 512;

/** 单次执行转发给界面的输出上限（字符）。超过即停发并提示，命令继续跑完。 */
export const MAX_OUTPUT_CHARS = 200_000;

/**
 * 单条命令的看门狗上限（毫秒）。
 *
 * 10 分钟是**全仓最慢那条预设**（`pnpm test:coverage`，实测冷跑数分钟）留出的
 * 余量，而 `pnpm check:all` 在全量门禁下也在这个量级。它保护的是「界面上没有
 * 第二个人能再点一次」这件事——看门狗到点掐整棵树，用户看到的是「已回收」，
 * 而不是一个永远转圈的控制台。
 */
export const MAX_RUN_MS = 10 * 60 * 1000;

/** 保留的**已完成**运行条数（在内存里，供界面回看这一次会话跑过什么）。
 *
 * 只保留最近的，且刻意不落库：控制台的输出是「看现场的」，把它做成持久历史会
 * 引出「该保留多久、多大、谁清理」一整串问题，而它要解决的是「别开终端」——
 * 已经跑过的、需要留档的命令，结论都该落在文件里（日志 / 报告），不是在
 * 一个会话级的滚动缓冲里。 */
export const MAX_HISTORY_ENTRIES = 50;
