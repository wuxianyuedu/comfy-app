/* ── 设置页「启动日志」的数据契约（两端共用）────────────────────────────
 *
 * 这个模块**只剩契约**：`LogSessionMeta` 与 `LogSessionsPayload`。两端共用的
 * 类型写在一边（端点或客户端）必然出现「服务端改了字段、客户端还在按旧字段
 * 读」的静默漂移，因此它独立成一个叶子模块。
 *
 * ## 这一层前后换过三次口径（ISSUE #1326 → #1587）
 *
 *   1. 最初按**文件内的 `▶` 横幅**切会话 —— 可见性止于应用退出，且靠人认边界；
 *   2. 中间改成**应用运行包**（`log/runs/<日期>_<时分秒>-<runId>/`）——
 *      跨运行那层解决了，但正文要靠「当前包 − 前一包」的长度减法去切，而减法
 *      依赖「包 N ⊇ 包 N-1」这条来自归档复制语义的性质；
 *   3. 改成**一次启动一份文件**（用户原话：「这四份也要改成每个文件只存储
 *      单次运行的历史，单次里如果执行多次也存放多个文件，这样看起来清晰」）
 *      —— 列表 = 该来源在 `log/current/services/` 下的单次文件，正文 = **整份
 *      文件**。切分判据彻底消失，因为「文件是谁」不依赖任何假设；
 *   4. **再加跨包**（ISSUE #1587，用户原话：「日志会归档到 runs 中，但应用内
 *      缺少入口查看」）—— 3 只解决了**包内**：`current/` 被归档、清空之后，
 *      `runs/` 里那一包中的份没有任何界面能打开。归档是整目录复制 ⇒ 包内结构与
 *      `current/` 逐字同构 ⇒ 跨包就是「把各包里的文件排成一条时间线」，**复用**
 *      3 的判据，一条减法都没加回来。
 *
 * 四次都只动这一层与它的 IO，不动横幅的写侧：横幅的价值是**人直接打开文件时**
 * 看得出边界，与「谁在这里切会话」是两件事。
 */

/**
 * 下拉的一项（一次启动的一份日志文件）。
 *
 * `id` 有两种**已登记**的形态（见 `log-run-packs.ts` 的 `packScopedId`）：
 * `current/` 下的份是裸文件名，归档份是 `<包名>/<文件名>`。客户端原样回传即可，
 * **不解析它** —— 形态判据只在服务端一处。
 */
export interface LogSessionMeta {
  /** 该次运行异常退出（归档包 `run.json` 的 `crashed`）；`current` 恒为 false。 */
  crashed: boolean;
  /**
   * 份的 id（也是下拉的 value）：`current/` 的份是文件名
   * （`comfyui-runtime-20261005-093612.log`），归档份是 `<包名>/<文件名>`。
   *
   * 它就是那一份文件本身，不必再编码一次；带包名是为了让两个包里的同名份
   * （同一秒内两次启动的 `-2`、迁移前的旧固定名）不撞成一个 id。
   */
  id: string;
  /** `current` = 正在写的本次运行；`runs` = 已归档的历史运行包。 */
  scope: "current" | "runs";
  /** 该次启动的时刻（毫秒）；迁移前的旧固定名读不出时刻，为 null。 */
  startedAt: number | null;
  /**
   * 下拉文案（`09-30 19:36:12 · 正常退出 · a1b2c3`，由 `lib/log/log-run-packs`
   * 的 `formatScopedLabel` 拼好）。三段都有必要：同一次运行里多次启动的份只有
   * **时刻**能区分、崩溃那次的日志形态与正常退出完全不同（先标出来用户才知道
   * 在看什么）、runId 是跨包 `grep <runId> log/current log/runs/` 的唯一入口。
   */
  title: string;
}

/**
 * `GET /api/logs/sessions` 的响应体。
 *
 * 定义在这里而不是端点或客户端任一侧：它是**两端共用的契约**，写在一边就会
 * 出现「服务端改了字段、客户端还在按旧字段读」的静默漂移。
 */
export interface LogSessionsPayload {
  /** 选中那一份的正文（超长时取**尾部窗口**，见 `truncated` / `windowed`）。 */
  content: string;
  /** 本次返回的正文属于哪一份文件；没有可用会话时为 null。 */
  selectedId: string | null;
  /**
   * 可选的份（**新→旧，第一项就是最新、也恒是「本次运行」的那一份**），已按上限裁剪。
   *
   * 列表**跨两处**：本次运行（`log/current/services/`）恒在最前，其后是各历史
   * 运行包（`log/runs/<包名>/services/`）里的份、按包名倒序（ISSUE #1587 ——
   * 归档之后那些份此前**没有任何界面能打开**）。视图侧「新一次启动自动切过去」
   * 取的就是 `sessions[0]`，与端点 `selectedId` 的缺省值同端。
   */
  sessions: Array<LogSessionMeta>;
  /** 该份文件的字节数（排障与页脚展示）。 */
  size: number;
  /**
   * 这个来源一共有几份启动日志（**不受列表上限影响**）。
   *
   * 界面据此说明「更早的启动不在列表里」：一次启动一份文件之后，同一天可能攒
   * 几十份（服务被反复重启），下拉列不完 —— 不说的话用户会以为「只启动过这些次」。
   */
  total: number;
  /** 正文被截断（界面据此提示只见最近一段）。 */
  truncated: boolean;
  /** 服务端只扫了尾部窗口 —— 前面还有没读到的内容。 */
  windowed: boolean;
}
