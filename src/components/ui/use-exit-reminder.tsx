"use client";

// ── 「离开这一屏就丢掉现场」的唯一出口（规范 10.3.1 / 06 §6.7 第 ③ 档）───
//
// 本轮把「视图层自己写站点级过渡」那批账（台账 F2）排了一遍，发现它们可以
// 分成两族 —— 而**只有一族的收益是真的**：
//
//   · **「页面换掉但不像换过」**（路由切换 / 视图页签切换）：这一族**不做**。
//     App Router 只在 `loading.tsx` 存在时才把旧页面留到新页面就绪，
//     本仓库的 `loading.tsx` 只有全屏那一个（台账 F2），因此过渡态无处安放 ——
//     做出来是一次**更长的白屏**，而不是更平滑的切换。
//   · **「离开时会丢掉用户现场」**（编辑中的表单、没保存的草稿、选中的文件）：
//     这一族值得做，而且**现在的行为是错的** —— 内容凭空消失、没有任何提示。
//
// 本出口做第二族：**用无 JS 的 CSS 过渡**（`animation` + `:has()`）把
// 「离开会丢东西」这一格画出来。零运行时状态、零定时器、零依赖，
// 与服务端渲染天然兼容（不需要它是客户端组件做任何水合后的判断）。
//
// ## 它**不是**「确认对话框」
//
// 弹一个 `confirm()` 拦下来是另一件事（要接管导航、要跟 App Router 的
// 导航语义打架），本出口只负责**把后果说出来**。用 `window.confirm` 这类
// 同步阻塞对话框做这件事，在桌面壳里会卡住整个 webview —— 那比没有提示更糟。
//
// ## 为什么不用 JS 定时器
//
// 同一形态本仓库已有一份活样本：`ui/sonner` 那条「点进来闪一下」的提示。
// 用 `setTimeout` + `useState` 做**纯装饰**的自动消失，代价是卸载期
// `setState`、连点覆盖、时长散落 —— 而它换来的只是「提示多停留一会儿」。
// 落在这里的语义是「**只要还有东西会丢，这句话就在**」，天然不需要倒计时：
// 时间驱动换成状态驱动（`isDirty` 为真就一直亮），于是一整类缺陷不存在。
//
// ## 扩展新落点只需要两步
//
// 1. `globals.css` 里给这个落点加一条 `[data-exit-reminder]:has(<你的信号>)`
//    规则，把 `--exit-reminder-shown` 摆到 `inline`；
// 2. 在 JSX 里把 `<ExitReminder>` 放进**那个被导航整体替换掉的容器**里。
//
// 「被导航整体替换掉的容器」不是口味问题：提醒如果挂在导航**留驻**的祖先上，
// 它永远不会跟着走，也就永远不会亮 —— 那是这条判据最可能的静默失效方式。

/**
 * 这一屏「离开就丢」的提示条。
 *
 * 默认**不占位、不可见**：没有 `:has()` 信号命中时它整条不在（`display: none`），
 * 所以可以在任何容器里无条件渲染，不必让调用处先算一遍「现在该不该显示」。
 *
 * `role="status"` 而不是 `alert`：它是「当前状态」的播报（这件事一直在），
 * 不是「刚刚发生了什么」。读屏用户在它出现时被通知一次，之后不再重复打断。
 */
export function ExitReminder({
  children,
  className = "",
}: {
  children: React.ReactNode;
  /** 额外类名（内边距 / 圆角这类**布局**决定由调用处给）。 */
  className?: string;
}) {
  // 属性段落里不要插 JSX 花括号注释：它只能出现在子节点位置，写在属性之间会把
  // 属性段整段截断。
  return (
    // 文案本身是给读屏与「CSS 规则没命中」两种情况用的兜底 —— 后者不会发生
    // （`:has()` 在 Chromium 111+ 一定支持），但 `display:none` 的元素仍会被
    // 读屏的虚拟光标读到，写清楚总比留空好。
    <p data-exit-reminder="" role="status" className={className}>
      {children}
    </p>
  );
}

/**
 * 「这一屏有会丢的东西」的**信号**注册：把它挂在**提供信号的元素**上。
 *
 * 用 `data-` 属性而不是 class：属性是给 CSS 判据读的，class 是给样式读的，
 * 两者混在一起之后「这条 class 还有没有消费者」就再也数不清了
 * （规范 03 §3.6.1.1 那一族「豁免会过期」的教训）。
 *
 * 值可以是 `undefined`（表示「没有会丢的东西」）—— 属性会整条消失，
 * 与不写这个 prop 等价，于是调用处不必再写一层三元。
 */
export function exitReminderSignal(active: boolean): {
  "data-dirty": string | undefined;
} {
  return { "data-dirty": active ? "" : undefined };
}
