/**
 * 居中模态卡片的**宽度档**（规范 17 §17.2 第①层：常量 + 纯派生，无 React、无 DOM）。
 *
 * 为什么单独立一个模块：宽度是「删掉 JSX 还能不能判定」的事实 —— 弹窗自己要多宽、
 * 加宽态要多宽、调用处怎么写才不会**静默失效**，三者必须同源。散在几个组件的
 * 模板串里各写一份，就是同一件事有多处口径（§12.12 的孪生对正是这么长出来的）。
 *
 * ── 加宽按钮为什么此前「按了没反应」（ISSUE #720）──────────────────────
 * `DialogContent` 的 Popup 带 `max-w-[calc(100%-2rem)]`，表达的是「内建卡片不贴满
 * 视口两侧」。调用处传 `popupClassName="max-w-[96vw]"` 想去掉它时，**两个
 * `max-w-*` 属同一族**，谁赢由 Tailwind 的**输出顺序**决定 —— 真实 Chromium
 * （1430×900）实测：加宽态量到的不是 6vw 的余量，而是基元那句 `calc(100%-2rem)`
 * 的结果，**宽度一个字都没变**。
 *
 * 所以这里的档位带的是 `w-*` 而不是 `max-w-*`：宽度族与上限族不同族，宽度直接
 * 给出结论；`max-w-*` 只在「视口比它还窄」时继续兜底（那是它该管的事）。
 * 加宽因此一定带来可见变化，而不是「看起来像没生效」。
 *
 * 加宽档取 `calc(100vw-16px)`：它的语义是**贴视线两边的「看全」档**，只让出 8px
 * 让卡片不贴边。此前写的 `96vw` 在 1500px 级窗口下还行，窗口一大就被摊薄。
 */

/** 居中卡片的宽度档：默认档由调用处按内容密度给，加宽档统一。 */
export interface ModalWidth {
  /** 默认档（弹窗刚打开时）。 */
  base: string;
  /** 加宽档（标题栏的「加宽」按钮）。 */
  wide: string;
}

/** 加宽档对每个调用处都一样：贴满内容区，只留 8px。 */
export const MODAL_WIDE_WIDTH = "w-[calc(100vw-16px)]";

/** 按默认档拼出宽度档。调用处只决定「默认多宽」——内容密度由它决定
 *  （应用日志四列、执行日志三列，天然不同），加宽档是同一件事。 */
export function modalWidth(base: string): ModalWidth {
  return { base, wide: MODAL_WIDE_WIDTH };
}
