export const OVERLAY_MAX_HEIGHT = "max-h-[85vh]";

/** 页面内自滚动区域的上限：比浮层矮一档，周围内容要留呼吸。 */
export const EMBEDDED_SCROLL_MAX_HEIGHT = "max-h-[70vh]";
