/**
 * 浮层的**最大高**档（规范 17 §17.2 第①层：常量 + 纯派生，无 React、无 DOM）。
 *
 * 为什么与 `dialog-width.ts` 同形、而不是把档位做成 `@theme` 里的 `--max-height-*`：
 * 实测 `cn("max-h-[85vh]", "max-h-overlay")` **两条都留** —— tailwind-merge 认不出
 * 自定义名字属于哪一族，于是「上限」这件事在调用点变成两条互相打架的声明，谁赢由
 * Tailwind 的输出顺序决定。这正是 `dialog-width.ts` 文件头记着的那次事故（ISSUE #720：
 * 加宽按钮按了没反应）的另一半，而它已经用「档位存 class 串」解决过一次。
 * 存字面量族（`max-h-[85vh]`）则不同：实测 `cn("max-h-[85vh]", "max-h-[70vh]")` 只留
 * 后一条 —— 同族冲突照常生效，调用点覆写仍然可预期。
 *
 * ── 两档是怎么量出来的（不是凑的）────────────────────────────────
 * `max-h-[85vh]` 6 处（居中模态、图片看全、下拉式弹层面板）—— 已经是事实档；
 * 另有 `78vh` 与 `90vh` 各 1 处，是同一角色上的两个漂移值（都是「浮层主体别顶满视口」，
 * 差 5–7 个百分点没有任何一处文档说过为什么）→ 并入 85vh。
 * `max-h-[70vh]` 3 处（坐在页面里、自己滚的内嵌卡片区）—— 角色与上面不同：它不是浮层，
 * 是「页面里的一块滚动区」，上限要留出周围内容的呼吸，所以单独一档。
 *
 * ── 刻意不收的两处（别当漏网清掉）──────────────────────────────
 * · `WorkflowNodeJsonPopover` 的 positioner `max-h-[60vh]`：贴边小面板，比内嵌区还要矮一档，
 *   目前只有它一个消费者 —— 为它立一档就是「为以后可能用得上」留在库里（同 `--text-hero`
 *   退役的理由）。
 * · `ConsoleView` 左栏的 `max-h-[45%]`：**百分比是相对父容器而不是视口**，量的是另一件事，
 *   与 vh 两档不同族。
 */

