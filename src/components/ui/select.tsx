function SelectContent({
  className,
  children,
  side = "bottom",
  sideOffset = 4,
  align = "center",
  alignOffset = 0,
  /* 默认 **false**（不把「已选项」对齐到触发器）：base-ui 的原生默认是 true，
     它让弹层位置随选中项上下移动 —— 选中末尾项时弹层被顶到视口上方、前半截
     出屏。需要「原生 select 观感」（弹层盖住触发器）的调用处显式传 true。
     同款修复见 `ui/select-menu` 与规范 07 §7.21.4。 */
  alignItemWithTrigger = false,
  collisionAvoidance,
  positionerClassName,
  ...props
}: SelectPrimitive.Popup.Props &
  Pick<
    SelectPrimitive.Positioner.Props,
    | "align"
    | "alignOffset"
    | "side"
    | "sideOffset"
    | "alignItemWithTrigger"
    | "collisionAvoidance"
  > & {
    /* 定位层（portal 宿主）的额外 class。层级必须在**这一层**给：Popup 自己的
       层级只在 positioner 建立的 stacking context 内部生效，改它不解决被外层
       遮罩压住的问题（清单见 §16.2.5 与 ISSUE #262）。 */
    positionerClassName?: string;
  }) {
  /* 浮层可用区域：视口减去应用级标题行（壳态）—— 见 `useOverlayBoundary`。 */
  const boundary = useOverlayBoundary();
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Positioner
        side={side}
        sideOffset={sideOffset}
        align={align}
        alignOffset={alignOffset}
        alignItemWithTrigger={alignItemWithTrigger}
        /* 撞到视口边界时的行为由调用方决定：日志面板要求弹层**始终从扳机下方
           展开**（`side: "none"`），宁可让弹层自己滚动，也不要翻到上面去把头部
           顶到窗口外（ISSUE #262）。 */
        collisionAvoidance={collisionAvoidance}
        /* 层级默认取刻度表的 `popup` 档（规范 16 §16.2.5）：它高于 `modal`，
           所以模态遮罩里的下拉不会被整块压住（弹层画得出来却**收不到指针事件**，
           ISSUE #262）。调用方需要另行指定时用 positionerClassName 覆盖。 */
        className={cn(positionerClassName ?? "z-popup isolate")}
        collisionBoundary={boundary ?? undefined}
      >
        <SelectPrimitive.Popup
          data-slot="select-content"
          data-align-trigger={alignItemWithTrigger}
          className={cn(
            "border-border-strong bg-popover text-popover-foreground data-[side=bottom]:slide-in-from-top-2 data-[side=inline-end]:slide-in-from-left-2 data-[side=inline-start]:slide-in-from-right-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95 relative isolate z-50 max-h-(--available-height) w-(--anchor-width) min-w-36 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-lg border shadow-lg ring-1 shadow-black/5 ring-(--ring-shadow) duration-100 data-[align-trigger=true]:animate-none dark:shadow-black/40",
            className,
          )}
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.List>{children}</SelectPrimitive.List>
          <SelectScrollDownButton />
        </SelectPrimitive.Popup>
      </SelectPrimitive.Positioner>
    </SelectPrimitive.Portal>
  );
}

